"""Build assets/svy-sample.js from the ONS Census 2021 public microdata teaching sample.

Source: Office for National Statistics, "Public microdata teaching sample, England and Wales:
Census 2021" (1% of person records), upload-publicmicrodatateachingsample.csv, Open Government
Licence v3.0. Download it yourself from ons.gov.uk and pass its path:

    python3 materials/build-svy-sample.py /path/to/upload-publicmicrodatateachingsample.csv

Kept: adults aged 16 and over (resident_age_7d 2..7) with a general-health answer (not -8).
Drawn: a seeded sample of 20,000 of them, the bench's stand-in "Ottervale" population.
Streets: residents are grouped into simulated streets of 20 within each area, ordered by age band
plus noise, so neighbours resemble each other. The grouping is SIMULATED and labelled.
Output is generated with json.dumps (never string interpolation).
"""
import json
import random
import sys
from pathlib import Path

import pandas as pd

SEED = 20211
N = 20000
STREET = 20
REGIONS = ["E12000001", "E12000002", "E12000003", "E12000004", "E12000005",
           "E12000006", "E12000007", "E12000008", "E12000009", "W92000004"]
REGION_NAMES = ["North East", "North West", "Yorkshire and The Humber", "East Midlands",
                "West Midlands", "East of England", "London", "South East", "South West", "Wales"]


def econ3(v: int) -> int:
    if v in (1, 2, 3, 4):
        return 0  # economically active
    if v == 5:
        return 1  # retired
    return 2      # other inactive (student, home, long-term sick, other)


def main(csv_path: str) -> None:
    d = pd.read_csv(csv_path)
    rows_in = len(d)
    a = d[(d.resident_age_7d >= 2) & (d.health_in_general > 0)].copy()
    adults = len(a)
    a["bad"] = (a.health_in_general >= 3).astype(int)
    full_share = float(a.bad.mean())
    a = a.sort_values("resident_id_m").reset_index(drop=True)
    rng = random.Random(SEED)
    idx = sorted(rng.sample(range(len(a)), N))
    s = a.iloc[idx].reset_index(drop=True)

    recs = []
    for r in s.itertuples():
        recs.append({
            "age": int(r.resident_age_7d) - 2,          # 0..5 = 16-24 .. 65+
            "sex": int(r.sex) - 1,                      # 0 female, 1 male
            "area": REGIONS.index(r.region),            # 0..9
            "comm": int(r.residence_type) - 1,          # 1 = communal establishment
            "econ": econ3(int(r.economic_activity_status_10m)),
            "bad": int(r.bad),
            "noise": rng.random(),
        })
    # order by area, then age band plus noise (1.5 bands) (simulated streets of similar neighbours)
    recs.sort(key=lambda z: (z["area"], z["age"] + 1.5 * z["noise"]))
    streets = []
    for ar in range(10):
        cnt = sum(1 for z in recs if z["area"] == ar)
        full, rest = divmod(cnt, STREET)
        streets += [STREET] * full + ([rest] if rest else [])
    codes = []
    for z in recs:
        c = ((((z["age"] * 2 + z["sex"]) * 10 + z["area"]) * 2 + z["comm"]) * 3 + z["econ"]) * 2 + z["bad"]
        codes.append(c)
    data = {
        "source": "ONS, Public microdata teaching sample, England and Wales: Census 2021 (1% sample), Open Government Licence v3.0",
        "licence": "Contains public sector information licensed under the Open Government Licence v3.0.",
        "rowsInFile": rows_in,
        "adultsWithHealthAnswer": adults,
        "fullFileShareBad": round(full_share, 6),
        "seed": SEED,
        "n": N,
        "areas": REGION_NAMES,
        "ages": ["16-24", "25-34", "35-44", "45-54", "55-64", "65+"],
        "streets": streets,
        "codes": codes,
    }
    out = Path(__file__).resolve().parent.parent / "assets" / "svy-sample.js"
    out.write_text("/* Generated by materials/build-svy-sample.py. Real census rows (ONS 2021 teaching sample, OGL v3.0); streets simulated. */\n"
                   "window.SVY_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"rows in file {rows_in}, adults with health answer {adults}, full-file share fair-or-worse {full_share:.4f}")
    print(f"kept {N}, streets {len(streets)}, share in sample {sum(c % 2 for c in codes) / N:.4f}, bytes {out.stat().st_size}")


if __name__ == "__main__":
    main(sys.argv[1])
